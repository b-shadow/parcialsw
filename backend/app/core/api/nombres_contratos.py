def traducir_json(valor, *, al_espanol: bool):
    if isinstance(valor, list):
        return [traducir_json(item, al_espanol=al_espanol) for item in valor]
    if not isinstance(valor, dict):
        return valor
    mapa = TRADUCCIONES if al_espanol else INVERSAS
    return {mapa.get(clave, clave): traducir_json(item, al_espanol=al_espanol)
            for clave, item in valor.items()}
