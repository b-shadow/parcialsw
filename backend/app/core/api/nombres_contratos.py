def nombre_espanol(clave: str) -> str:
    if clave in CAMPOS:
        return CAMPOS[clave]
    if clave in ESPECIALES:
        return ESPECIALES[clave]
    return "_".join(PALABRAS.get(parte, parte) for parte in clave.split("_"))


